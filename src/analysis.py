"""Analyze existing run artifacts by cumulative dollars; never calls a model."""
import argparse
import csv
import json
import os
from pathlib import Path

REPORT_MARKER = '<!-- generated by analysis.py -->'


def summarize_arm(arm, data, budget):
    points = []
    cost = elapsed = 0.0
    complete = True
    within = None
    for row in data['trajectory']:
        observed = row.get('observed_cost_usd')
        if observed is None:
            observed = row.get('estimated_cost_usd') or 0.0
        cost += observed
        elapsed += row['elapsed_seconds']
        complete &= row.get('estimated_cost_usd') is not None
        point = {'arm': arm, 'iteration': row['iteration'], 'cumulative_cost_usd': cost,
                 'cumulative_elapsed_seconds': elapsed, 'cost_complete': complete,
                 'score': row['score'], 'best_score': row['best_score'],
                 'best_path': row['best_path'], 'status': row['status'],
                 'selected_parent_rank': row.get('selected_parent_rank'),
                 'selection_cost_usd': row.get('selection_usage', {}).get('observed_cost_usd', 0),
                 'within_budget': (budget is None or cost <= budget) if complete else None}
        points.append(point)
        # Incomplete accounting cannot establish a score at a particular dollar budget.
        if point['within_budget'] and complete and point['best_score'] is not None:
            within = point
    last = points[-1] if points else None
    return {'stop_reason': data['stop_reason'], 'attempts': max(0, len(points) - 1),
            'known_cost_usd': cost, 'cost_complete': complete,
            'elapsed_seconds': elapsed, 'final_best_score': last['best_score'] if last else None,
            'final_best_path': last['best_path'] if last else None,
            'best_at_or_below_budget': within,
            'overshoot_usd': max(0.0, cost - budget) if budget is not None else None,
            'points': points}


def write_analysis(directory, summary):
    directory = Path(directory)
    config_path = directory / 'run_config.json'
    config = json.loads(config_path.read_text()) if config_path.exists() else summary
    budget = config.get('budget_usd_per_arm')
    report = {'status': summary.get('status', 'legacy_or_in_progress'),
              'selector_comparison': config.get('selector') == 'compare',
              'budget_usd_per_arm': budget,
              'cost_note': 'Configured estimates, not invoices. Incomplete costs are lower bounds.',
              'comparison_note': 'Compare complete-accounting step curves at common cumulative cost; do not interpolate or include a budget-crossing child in the within-budget endpoint.',
              'arms': {arm: summarize_arm(arm, data, budget) for arm, data in summary['arms'].items()}}
    plots = directory / 'plots'
    plots.mkdir(exist_ok=True)
    points = [p for arm in report['arms'].values() for p in arm['points']]
    if points:
        with (plots / 'curve.csv').open('w', newline='') as output:
            writer = csv.DictWriter(output, fieldnames=list(points[0]))
            writer.writeheader()
            writer.writerows(points)
    lines = [REPORT_MARKER, f"# Budget comparison ({report['status']})", '',
             f'Budget per arm: {budget}. Costs are estimates, not invoices.', '',
             '| Arm | Attempts | Known cost | Cost complete | Best confirmed within budget | Final best | Known overshoot | Stop reason |',
             '|---|---:|---:|---|---:|---:|---:|---|']
    def fmt(value):
        return 'unknown' if value is None else f'{value:.6f}'
    for name, arm in report['arms'].items():
        within = arm['best_at_or_below_budget']
        lines.append(f"| {name} | {arm['attempts']} | ${arm['known_cost_usd']:.6f} | {arm['cost_complete']} | "
                     f"{fmt(within['best_score'] if within else None)} | {fmt(arm['final_best_score'])} | "
                     f"{fmt(arm['overshoot_usd'])} | {arm['stop_reason']} |")
    lines += ['', 'Within-budget scores exclude a child completed after crossing the budget. '
              'An unfinished search may have spent substantially less than the budget. '
              'Missing cost estimates prevent an equal-dollar claim. '
              'A confirmed within-budget score remains valid even if later costs are incomplete; '
              'it is then only the best from the fully accounted prefix. '
              'The raw trajectory retains failures and all spending.', '',
              'Use [curve.csv](plots/curve.csv) for the full step curve. Model calls, code, prompts, '
              'evaluations and internal agent tests remain in the candidate directories.', '',
              '![Score versus cost](plots/score_vs_cost.png)', '',
              '![Score versus time](plots/score_vs_time.png)', '',
              'Elapsed time includes generation and evaluation within each arm. '
              'The arms are independent searches, not simultaneous runs.', '']
    report_path = directory / 'report.md'
    if report['selector_comparison']:
        lines += ['![Selected parent rank](plots/parent_rank.png)', '',
                  '![Selection and generation cost](plots/cost_breakdown.png)', '',
                  'Both arms start from the same naive seed with independent pools. '
                  'Selector cost is included. One eligible candidate needs no LLM call. '
                  'Invalid selection output falls back to the best candidate without retry. '
                  'Unknown costs stop an arm. This is one exploratory run per condition.', '']
    # Rebuilding plots must not erase a researcher's interpretation or caveats.
    if not report_path.exists() or report_path.read_text().startswith(REPORT_MARKER):
        report_path.write_text('\n'.join(lines))
    return report


def plot_analysis(directory, report, *, detail=False):
    from .config import ROOT
    os.environ.setdefault('MPLCONFIGDIR', str(ROOT / '.tools/state/cache/matplotlib'))
    import matplotlib
    matplotlib.use('Agg')
    import matplotlib.pyplot as plt
    plots = Path(directory) / 'plots'
    plots.mkdir(exist_ok=True)
    views = [('cost', 'Cumulative API cost (USD)', 1, False),
             ('time', 'Elapsed time per arm (hours)', 3600, False)]
    if detail:
        views.append(('cost', 'Cumulative API cost (USD)', 1, True))
    names = {'direct': 'Direct LLM', 'opencode': 'OpenCode Agent',
             'opencode_best': 'OpenCode + best-score', 'opencode_llm': 'OpenCode + LLM-select',
             'direct_best': 'Direct + best-score', 'direct_llm': 'Direct + LLM-select'}
    colors = {'direct': '#2878B5', 'opencode': '#E07B39',
              'opencode_best': '#2878B5', 'opencode_llm': '#E07B39'}
    for axis, xlabel, divisor, zoom in views:
        key = 'cumulative_cost_usd' if axis == 'cost' else 'cumulative_elapsed_seconds'
        fig, ax = plt.subplots(figsize=(8, 4.8))
        for name, arm in report['arms'].items():
            points = [p for p in arm['points'] if p['best_score'] is not None]
            if points:
                color = colors.get(name)
                # Draw recorded estimates uniformly; accounting details stay in the report.
                line, = ax.step([p[key] / divisor for p in points], [p['best_score'] for p in points],
                                where='post', color=color, linewidth=2,
                                label=names.get(name, name))
                ax.scatter([p[key] / divisor for p in points],
                           [p['best_score'] for p in points], color=line.get_color(),
                           s=12, alpha=.55, zorder=3, linewidths=0)
                improvements = [p for i, p in enumerate(points)
                                if i == 0 or p['best_score'] < points[i - 1]['best_score']]
                ax.scatter([p[key] / divisor for p in improvements],
                           [p['best_score'] for p in improvements], color=line.get_color(),
                           s=26, zorder=3, edgecolors='white', linewidths=.5)
        if axis == 'cost' and report['budget_usd_per_arm'] is not None:
            budget = report['budget_usd_per_arm']
            ax.axvline(budget, color='#999999', linestyle='--', linewidth=1)
            ax.text(budget, 1.015, f'${budget:g} budget', transform=ax.get_xaxis_transform(),
                    va='bottom', ha='right', fontsize=9, color='#666666')
        ax.set(xlabel=xlabel, ylabel='Best scheduler score (s; lower is better)',
               title='Scheduler optimization' + (' — detail' if zoom else ''))
        if zoom:
            values = [p['best_score'] for arm in report['arms'].values()
                      for p in arm['points'] if p['iteration'] > 0 and p['best_score'] is not None]
            if values:
                padding = max((max(values) - min(values)) * .1, 1)
                ax.set_ylim(max(0, min(values) - padding), max(values) + padding)
        else:
            ax.set_ylim(bottom=0)
        ax.set_xlim(left=0)
        ax.spines[['top', 'right']].set_visible(False)
        ax.grid(alpha=.18)
        if ax.lines:
            ax.legend(frameon=False, loc='upper right')
        note = 'Small dots: recorded iterations. Large dots: new best. Costs are estimates.'
        if zoom:
            note += ' Seed is above this view.'
        fig.text(.13, .015, note,
                 fontsize=8, color='#666666')
        fig.tight_layout(rect=(0, .035, 1, 1))
        suffix = '_detail' if zoom else ''
        fig.savefig(plots / f'score_vs_{axis}{suffix}.png', dpi=200)
        plt.close(fig)
    if report.get('selector_comparison'):
        fig, ax = plt.subplots(figsize=(8, 4))
        for name, arm in report['arms'].items():
            points = [p for p in arm['points'] if p['selected_parent_rank'] is not None]
            ax.plot([p['iteration'] for p in points], [p['selected_parent_rank'] for p in points],
                    marker='o', label=names.get(name, name), color=colors.get(name))
        ax.set(xlabel='Outer iteration', ylabel='Selected parent rank (1 = best)', ylim=(.5, None))
        from matplotlib.ticker import MaxNLocator
        ax.yaxis.set_major_locator(MaxNLocator(integer=True))
        ax.legend(frameon=False)
        fig.tight_layout()
        fig.savefig(plots / 'parent_rank.png', dpi=200)
        plt.close(fig)
        fig, ax = plt.subplots(figsize=(8, 4))
        labels = [names.get(name, name) for name in report['arms']]
        selection = [sum(p['selection_cost_usd'] for p in a['points']) for a in report['arms'].values()]
        generation = [a['known_cost_usd'] - s for a, s in zip(report['arms'].values(), selection)]
        ax.bar(labels, generation, label='Generation')
        ax.bar(labels, selection, bottom=generation, label='Parent selection')
        ax.set(ylabel='Recorded API cost (USD)')
        ax.legend(frameon=False)
        fig.tight_layout()
        fig.savefig(plots / 'cost_breakdown.png', dpi=200)
        plt.close(fig)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('directory', type=Path)
    parser.add_argument('--plot', action='store_true', help='compatibility flag; plots are always generated')
    parser.add_argument('--detail', action='store_true', help='also draw a cost plot zoomed after the seed')
    args = parser.parse_args()
    summary = json.loads((args.directory / 'results.json').read_text())
    report = write_analysis(args.directory, summary)
    plot_analysis(args.directory, report, detail=args.detail)
    print(args.directory / 'report.md')


if __name__ == '__main__':
    main()
